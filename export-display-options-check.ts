import assert from "node:assert/strict";
import { Chord, Note, Score, Part, Measure } from "./src/score/score";
import { Fraction } from "./src/common/fraction";
import { cloneExportScore, exportContinuationVoiceColor, resetExportNumberLabels } from "./src/editor/export-display";
import { applyKeyboardKeyLabels } from "./src/slashscore";

const score = new Score();
const part = new Part();
score.parts.push(part);
const measure = new Measure(0);
part.measures.push(measure);
const first = new Chord(measure);
const last = new Chord(measure);
first.duration = new Fraction(1, 4);
last.duration = new Fraction(1, 4);
measure.entries.push(first, last);
const start = new Note(first);
const end = new Note(last);
Object.assign(start, { pitch: 60, number: "1", jpOctave: 0, tieStart: true });
Object.assign(end, { pitch: 60, number: "1", jpOctave: 0, tieEnd: true });
start.tieNext = end; end.tiePrev = start;
first.add(start); last.add(end);
const { score: clone, copies } = cloneExportScore(score);
const clonedStart = copies.get(start) as Note;
const clonedEnd = copies.get(end) as Note;
assert.ok(clone instanceof Score);
assert.ok(clonedStart instanceof Note);
assert.ok(clonedStart.chord.duration instanceof Fraction);
assert.equal(clonedStart.tieNext, clonedEnd);
assert.equal(clonedEnd.tiePrev, clonedStart);
assert.equal(clonedStart.chord.measure, clone.parts[0].measures[0]);
assert.notEqual(clone, score);
applyKeyboardKeyLabels(clone, false, true);
assert.equal(clonedStart.displayText, "A");
assert.equal(clonedEnd.displayHidden, true);
assert.equal(start.displayText, null);
assert.equal(end.displayHidden, false);
resetExportNumberLabels(clone);
assert.equal(clonedStart.displayText, null);
assert.equal(clonedEnd.displayHidden, false);
assert.equal(clonedStart.tieNext, clonedEnd);
assert.equal(clonedStart.pitch, start.pitch);
assert.equal(exportContinuationVoiceColor("#cc3344", clonedEnd, true), "#eaa9b0");
assert.equal(exportContinuationVoiceColor("#cc3344", clonedStart, true), "#cc3344");
assert.equal(exportContinuationVoiceColor("#cc3344", clonedEnd, false), "#cc3344");
console.log("Export score isolation and number/keyboard labels: passed");
